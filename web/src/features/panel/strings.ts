const DICT: Record<Lang, Record<PKey, string>> = { uk, en };

export function pt(key: PKey, lang: Lang, params?: Record<string, string | number>): string {
  const s = DICT[lang][key];
  return params ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : s;
}
